import mongoose from 'mongoose';

const projectSchema = new mongoose.Schema({
  ownerId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
  title: { type: String, required: true, trim: true, maxlength: 100 },
  type: { type: String, enum: ['interior', 'exterior', '3d', 'renovation'], required: true },
  room: { type: String, trim: true, maxlength: 60 },
  roomType: { type: String, trim: true, maxlength: 80 },
  style: { type: String, trim: true, maxlength: 60 },
  palette: { type: String, trim: true, maxlength: 60 },
  budget: { type: String, trim: true, maxlength: 40 },
  layout: { type: String, trim: true, maxlength: 40 },
  doors: { type: Number, min: 0, max: 20 },
  windows: { type: Number, min: 0, max: 20 },
  prompt: { type: String, trim: true, maxlength: 2000 },
  imageKey: { type: String, trim: true, match: /^photo-[a-zA-Z0-9-]{4,80}$/ },
  estimate: { type: Number, min: 0, max: 100000000 },
  favorite: { type: Boolean, default: false },
  archived: { type: Boolean, default: false },
  rooms: [{
    name: { type: String, trim: true, maxlength: 60 },
    length: { type: Number, min: 0, max: 60 },
    width: { type: Number, min: 0, max: 60 },
    height: { type: Number, min: 0, max: 20 },
    openingsArea: { type: Number, min: 0, max: 500 },
    notes: { type: String, trim: true, maxlength: 200 },
  }],
  shareToken: { type: String, unique: true, sparse: true },
  sharedAt: { type: Date },
  measurements: {
    length: { type: Number, min: 0, max: 60 },
    width: { type: Number, min: 0, max: 60 },
    height: { type: Number, min: 0, max: 20 },
    openingsArea: { type: Number, min: 0, max: 500 },
    unit: { type: String, enum: ['ft'], default: 'ft' },
    city: { type: String, trim: true, maxlength: 60 },
  },
  estimateReport: {
    renovationType: { type: String, trim: true, maxlength: 80 },
    quality: { type: String, trim: true, maxlength: 30 },
    low: { type: Number, min: 0, max: 100000000 },
    expected: { type: Number, min: 0, max: 100000000 },
    high: { type: Number, min: 0, max: 100000000 },
    currency: { type: String, enum: ['INR'], default: 'INR' },
    items: [{
      key: { type: String, maxlength: 40 },
      name: { type: String, required: true, maxlength: 100 },
      quantity: { type: Number, min: 0, max: 1000000 },
      unit: { type: String, maxlength: 40 },
      unitRate: { type: Number, min: 0, max: 1000000 },
      low: { type: Number, min: 0, max: 100000000 },
      expected: { type: Number, min: 0, max: 100000000 },
      high: { type: Number, min: 0, max: 100000000 },
    }],
    shoppingList: [{
      name: { type: String, required: true, maxlength: 100 },
      quantity: { type: Number, min: 0, max: 1000000 },
      unit: { type: String, maxlength: 40 },
    }],
    assumptions: [{ type: String, trim: true, maxlength: 240 }],
  },
  sourceImageUrl: { type: String, trim: true },
  sourceAssetId: { type: mongoose.Schema.Types.ObjectId, ref: 'DesignAsset' },
  referenceAssetId: { type: mongoose.Schema.Types.ObjectId, ref: 'DesignAsset' },
  saved: { type: Boolean, default: true },
  generations: [{
    mode: { type: String, enum: ['interior', 'exterior', '3d'], required: true },
    roomType: { type: String, required: true, maxlength: 80 },
    style: { type: String, required: true, maxlength: 60 },
    palette: { type: String, required: true, maxlength: 60 },
    budget: { type: String, required: true, maxlength: 40 },
    layout: { type: String, trim: true, maxlength: 40 },
    doors: { type: Number, min: 0, max: 20 },
    windows: { type: Number, min: 0, max: 20 },
    instructions: { type: String, maxlength: 1500 },
    originalAssetId: { type: mongoose.Schema.Types.ObjectId, ref: 'DesignAsset', required: true },
    generatedAssetId: { type: mongoose.Schema.Types.ObjectId, ref: 'DesignAsset', required: true },
    model: { type: String, required: true },
    createdAt: { type: Date, default: Date.now },
  }],
  generatedImages: [{ url: String, createdAt: { type: Date, default: Date.now } }],
  status: { type: String, enum: ['draft', 'queued', 'processing', 'complete', 'failed'], default: 'draft' },
}, { timestamps: true });

projectSchema.index({ ownerId: 1, favorite: 1, updatedAt: -1 });
projectSchema.index({ ownerId: 1, saved: 1, archived: 1, updatedAt: -1 });

export default mongoose.models.Project || mongoose.model('Project', projectSchema);
